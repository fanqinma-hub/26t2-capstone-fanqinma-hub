import { sizeWordsUnit } from '@/content/size-words';
import { selectSessionMetrics } from '@/session/session-selectors';
import type { SessionMetrics } from '@/types/metrics.types';
import type { ReportViewModel } from '@/types/report.types';
import type { SessionState } from '@/types/session.types';

function completionDate(value: string | null) {
  if (!value) return 'Not recorded';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return 'Not recorded';
  return new Intl.DateTimeFormat('en-AU', { dateStyle: 'medium' }).format(date);
}

function scenarioFor(metrics: SessionMetrics): ReportViewModel['parent']['scenarioId'] {
  const score = metrics.readinessRate ?? metrics.adjectiveUseRate ?? 0;
  if (metrics.activity5.usedAllSix || score >= 0.85) return 'strong';
  if (score >= 0.7) return 'ready';
  if (score >= 0.35) return 'developing';
  return 'low';
}

function summaryFor(metrics: SessionMetrics) {
  if (metrics.totalUtterances === 0) {
    return 'No valid recorded utterances are available for this session yet.';
  }
  const usedWords = metrics.wordEvidence
    .filter((evidence) => evidence.status === 'USED')
    .map((evidence) => evidence.word);
  const words = usedWords.length > 0 ? usedWords.join(', ') : 'no target size words yet';
  const rateText = metrics.adjectiveUseRate === null
    ? 'not available'
    : `${Math.round(metrics.adjectiveUseRate * 100)}%`;
  return `The recorded responses included ${words}. Size adjectives appeared in ${rateText} of valid utterances, providing a useful snapshot of expressive size-word use.`;
}

export function buildCurrentReportViewModel(session: SessionState): ReportViewModel {
  const metadata = session.reportMetadata;
  const metrics = selectSessionMetrics(session, sizeWordsUnit);
  const scenario = scenarioFor(metrics);
  const stars = { low: 1, developing: 3, ready: 4, strong: 5 } as const;
  const notUsed = metrics.wordEvidence
    .filter((evidence) => evidence.status !== 'USED')
    .map((evidence) => evidence.word);

  return {
    mode: session.mode,
    header: {
      childName: metadata.childName?.trim() || 'Not recorded',
      childAge: metadata.childAge ?? 0,
      therapistName: metadata.therapistName?.trim() || 'Not recorded',
      unitTitle: sizeWordsUnit.title,
      completionDate: completionDate(session.completedAt),
      durationMs: metrics.durationMs,
      unitAttemptNumber: session.unitAttemptNumber,
    },
    parent: {
      scenarioId: scenario,
      starRating: stars[scenario],
      summaryText: summaryFor(metrics),
      wordCards: metrics.wordEvidence,
      therapistNote: metadata.therapistNote ?? '',
      homeTip: {
        label: '5-minute activity',
        text:
          notUsed.length > 0
            ? `Try a size-word game using ${notUsed.slice(0, 3).join(', ')}. Point to everyday objects and take turns describing their size.`
            : 'Keep using size words during everyday play and take turns describing what you notice.',
      },
    },
    therapist: {
      totalUtterances: metrics.totalUtterances,
      sizeWordUtterances: metrics.sizeWordUtterances,
      adjectiveUseRate: metrics.adjectiveUseRate,
      tierCounts: metrics.tierCounts,
      scaffoldTaps: metrics.scaffoldTaps,
      replayTaps: metrics.replayTaps,
      uniqueKeywords: metrics.uniqueKeywords,
      wordStats: metrics.wordEvidence,
      readinessRate: metrics.readinessRate,
      activity5: metrics.activity5,
      activityRows: metrics.activityRows,
      nextStep: metadata.nextStep ?? '',
      ndisContext:
        'This report provides dated evidence of expressive vocabulary use for functional communication planning and clinical records.',
    },
  };
}

export function getCurrentReportDataNotice(
  session: SessionState,
  options: { isSampleData?: boolean; hydrationError?: string | null } = {},
) {
  if (options.hydrationError) {
    const fallback = options.isSampleData
      ? 'Showing clearly labelled sample data instead.'
      : 'Showing the last session still available in memory.';
    return `The saved session could not be loaded (${options.hydrationError}). ${fallback}`;
  }
  if (options.isSampleData) {
    return 'No recorded session is available. This is sample data for preview only and is not a child session record.';
  }
  if (session.mode === 'fixture') {
    return 'Showing fixture session data generated by the formal activity demo.';
  }
  return 'Showing recorded SessionState data. Child metadata, prompt help, replay counts, and activity progress are read from the current session contract.';
}
